// ==== app/holidays.js ====
// 日本の祝日を内蔵し、稼働日計算に自動適用する(SPEC.md 8章)。
// 出典・更新方法は SPEC.md の要確認事項。ここでは 2024〜2030 の内閣府公表データ + 振替休日を静的に持つ。
// 稼働日 = 平日(月〜金)かつ祝日でない日。

const Holidays = (() => {
  // 'YYYY-MM-DD' の基準日（国民の祝日。振替休日は下で自動算出）
  const BASE = [
    // 2024
    '2024-01-01','2024-01-08','2024-02-11','2024-02-12','2024-02-23','2024-03-20','2024-04-29',
    '2024-05-03','2024-05-04','2024-05-05','2024-05-06','2024-07-15','2024-08-11','2024-08-12',
    '2024-09-16','2024-09-22','2024-09-23','2024-10-14','2024-11-03','2024-11-04','2024-11-23',
    // 2025
    '2025-01-01','2025-01-13','2025-02-11','2025-02-23','2025-02-24','2025-03-20','2025-04-29',
    '2025-05-03','2025-05-04','2025-05-05','2025-05-06','2025-07-21','2025-08-11','2025-09-15',
    '2025-09-23','2025-10-13','2025-11-03','2025-11-23','2025-11-24',
    // 2026
    '2026-01-01','2026-01-12','2026-02-11','2026-02-23','2026-03-20','2026-04-29','2026-05-03',
    '2026-05-04','2026-05-05','2026-05-06','2026-07-20','2026-08-11','2026-09-21','2026-09-22',
    '2026-09-23','2026-10-12','2026-11-03','2026-11-23',
    // 2027
    '2027-01-01','2027-01-11','2027-02-11','2027-02-23','2027-03-21','2027-03-22','2027-04-29',
    '2027-05-03','2027-05-04','2027-05-05','2027-07-19','2027-08-11','2027-09-20','2027-09-23',
    '2027-10-11','2027-11-03','2027-11-23',
    // 2028
    '2028-01-01','2028-01-10','2028-02-11','2028-02-23','2028-03-20','2028-04-29','2028-05-03',
    '2028-05-04','2028-05-05','2028-07-17','2028-08-11','2028-09-18','2028-09-22','2028-10-09',
    '2028-11-03','2028-11-23',
    // 2029
    '2029-01-01','2029-01-08','2029-02-11','2029-02-12','2029-02-23','2029-03-20','2029-04-29',
    '2029-04-30','2029-05-03','2029-05-04','2029-05-05','2029-07-16','2029-08-11','2029-09-17',
    '2029-09-23','2029-09-24','2029-10-08','2029-11-03','2029-11-23',
    // 2030
    '2030-01-01','2030-01-14','2030-02-11','2030-02-23','2030-03-20','2030-04-29','2030-05-03',
    '2030-05-04','2030-05-05','2030-05-06','2030-07-15','2030-08-11','2030-08-12','2030-09-16',
    '2030-09-23','2030-10-14','2030-11-03','2030-11-04','2030-11-23',
  ];

  const set = new Set(BASE);

  // 振替休日: 祝日が日曜のとき、その後の最初の非祝日を休日にする。
  const sundayHolidays = BASE.filter(s => parseDate(s).getDay() === 0);
  for (const s of sundayHolidays) {
    let d = addDays(parseDate(s), 1);
    while (set.has(fmtDate(d))) d = addDays(d, 1);
    set.add(fmtDate(d));
  }

  function isHoliday(d) { return set.has(fmtDate(d)); }
  function isWorkingDay(d) { return !isWeekend(d) && !isHoliday(d); }

  // start〜end(両端含む)の稼働日数。start>end は 0。
  function countWorkingDays(start, end) {
    if (!start || !end || dayDiff(start, end) < 0) return 0;
    let n = 0;
    let d = new Date(start.getFullYear(), start.getMonth(), start.getDate());
    while (dayDiff(d, end) >= 0) {
      if (isWorkingDay(d)) n++;
      d = addDays(d, 1);
    }
    return n;
  }

  // start から数えて稼働日 count 日分の期間の終了日を返す(start自身が稼働日なら1日目)。
  function endAfterWorkingDays(start, count) {
    if (!start || count < 1) return start;
    let remaining = count;
    let d = new Date(start.getFullYear(), start.getMonth(), start.getDate());
    // start が非稼働日なら次の稼働日まで送る
    while (!isWorkingDay(d)) d = addDays(d, 1);
    while (remaining > 1) {
      d = addDays(d, 1);
      if (isWorkingDay(d)) remaining--;
    }
    return d;
  }

  // date が非稼働日なら、次の稼働日へ送る。
  function nextWorkingDay(date) {
    let d = new Date(date.getFullYear(), date.getMonth(), date.getDate());
    while (!isWorkingDay(d)) d = addDays(d, 1);
    return d;
  }

  return { isHoliday, isWorkingDay, countWorkingDays, endAfterWorkingDays, nextWorkingDay };
})();
